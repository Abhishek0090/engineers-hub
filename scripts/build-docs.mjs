#!/usr/bin/env node
// Regenerates docs/CURRICULUM.md from src/content (tracks, chapters, goals, most asked questions).
// Run: npm run docs   (npm run share runs it too, so shared copies always carry current docs)
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = process.cwd();
const CONTENT = join(ROOT, "src", "content");
const read = (p) => JSON.parse(readFileSync(join(CONTENT, p), "utf8"));

const AREAS = [
  ["fundamentals", "Fundamentals"],
  ["frontend", "Frontend"],
  ["backend", "Backend"],
  ["database", "Databases"],
  ["devops", "DevOps and Cloud"],
  ["career", "Career"],
];
const LEVELS = ["beginner", "intermediate", "advanced"];
const cap = (s) => s[0].toUpperCase() + s.slice(1);
const cell = (s) => String(s).replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();

const tracks = readdirSync(join(CONTENT, "tracks"))
  .filter((f) => f.endsWith(".json"))
  .map((f) => read(join("tracks", f)))
  .sort((a, b) => a.order - b.order);
const goals = read("goals.json");
const byId = new Map(tracks.map((t) => [t.id, t]));

const count = (t, pred = () => true) => t.chapters.reduce((n, c) => n + c.questions.filter(pred).length, 0);
const isInterview = (q) => q.type === "interview";
const totals = {
  tracks: tracks.length,
  chapters: tracks.reduce((n, t) => n + t.chapters.length, 0),
  questions: tracks.reduce((n, t) => n + count(t), 0),
  interview: tracks.reduce((n, t) => n + count(t, isInterview), 0),
  minutes: tracks.reduce((n, t) => n + t.chapters.reduce((m, c) => m + c.estMinutes, 0), 0),
};

// Same selection as src/lib/data/derive.ts topInterviewQuestions(): flagged first, then round-robin by chapter.
function mostAsked(track, limit = 15) {
  const flagged = [];
  const perChapter = [];
  for (const c of track.chapters) {
    const list = c.questions.filter(isInterview);
    flagged.push(...list.filter((q) => q.top).map((q) => ({ q, c })));
    perChapter.push(list.filter((q) => !q.top).map((q) => ({ q, c })));
  }
  const rest = [];
  for (let round = 0; rest.length + flagged.length < limit; round++) {
    const layer = perChapter.map((l) => l[round]).filter(Boolean);
    if (!layer.length) break;
    rest.push(...layer);
  }
  return [...flagged, ...rest].slice(0, limit);
}

const anchor = (t) => t.title.toLowerCase().replace(/[^a-z0-9 -]/g, "").trim().replace(/\s+/g, "-");
const out = [];
const w = (s = "") => out.push(s);

w("# Curriculum");
w();
w("What Software Engineers Hub covers, generated from `src/content` by `scripts/build-docs.mjs`.");
w("Do not edit this file by hand: run `npm run docs` (or `npm run share`) after changing content.");
w();
w(`Generated ${new Date().toISOString().slice(0, 10)}.`);
w();
w("## At a glance");
w();
w("| Tracks | Chapters | Questions | Interview questions | Study time |");
w("| --- | --- | --- | --- | --- |");
w(`| ${totals.tracks} | ${totals.chapters} | ${totals.questions.toLocaleString("en-US")} | ${totals.interview.toLocaleString("en-US")} | about ${Math.round(totals.minutes / 60)} hours of lessons |`);
w();
w("Every chapter has a lesson (sections with code examples), key points, links to official docs and a");
w("practice set: multiple choice, true or false, select all, fill the blank and interview questions with");
w("model answers. Each track page ends with its most asked interview questions.");
w();

w("## Goals");
w();
w("A goal is an ordered path through the tracks. Learners pick one on the dashboard.");
w();
w("| Goal | Daily XP | Path |");
w("| --- | --- | --- |");
for (const g of goals) {
  const path = g.trackIds.map((id) => (byId.has(id) ? byId.get(id).title : `${id} (coming soon)`)).join(", ");
  w(`| **${cell(g.title)}**: ${cell(g.tagline)} | ${g.dailyGoalXp} | ${cell(path)} |`);
}
w();

w("## Tracks");
w();
w("| Area | Track | Chapters | Questions | Interview |");
w("| --- | --- | --- | --- | --- |");
for (const [area, label] of AREAS)
  for (const t of tracks.filter((x) => x.area === area))
    w(`| ${label} | [${cell(t.title)}](#${anchor(t)}) | ${t.chapters.length} | ${count(t)} | ${count(t, isInterview)} |`);
const pending = [...new Set(goals.flatMap((g) => g.trackIds))].filter((id) => !byId.has(id));
if (pending.length) {
  w();
  w(`Coming soon (listed in goals, content not written yet): ${pending.join(", ")}.`);
}
w();

for (const [area, label] of AREAS) {
  const list = tracks.filter((t) => t.area === area);
  if (!list.length) continue;
  w(`## ${label}`);
  w();
  for (const t of list) {
    w(`### ${t.title}`);
    w();
    w(t.description);
    w();
    w(`${t.chapters.length} chapters, ${count(t)} questions, ${count(t, isInterview)} interview questions.`);
    w();
    w("| # | Chapter | Level | Minutes | Questions | Covers |");
    w("| --- | --- | --- | --- | --- | --- |");
    t.chapters.forEach((c, i) => {
      const covers = c.lesson.map((s) => s.heading).join("; ");
      w(`| ${i + 1} | ${cell(c.title)} | ${cap(c.level)} | ${c.estMinutes} | ${c.questions.length} | ${cell(covers)} |`);
    });
    w();
    const levels = LEVELS.map((l) => [l, t.chapters.filter((c) => c.level === l).length]).filter(([, n]) => n);
    w(`Levels: ${levels.map(([l, n]) => `${cap(l)} ${n}`).join(", ")}.`);
    w();
    const top = mostAsked(t);
    if (top.length) {
      w(`**Most asked ${t.title} interview questions**`);
      w();
      top.forEach(({ q, c }, i) => w(`${i + 1}. ${cell(q.prompt)} _(${cap(q.level ?? c.level)}${q.top ? ", most asked" : ""})_`));
      w();
    }
  }
}

writeFileSync(join(ROOT, "docs", "CURRICULUM.md"), out.join("\n"));
console.log(`docs/CURRICULUM.md: ${totals.tracks} tracks, ${totals.chapters} chapters, ${totals.questions} questions`);
